def derive_lsd():
    raw = base.read_csv(ROOT/'reports/single_clap_benchmark/per_example.csv')
    raw = [r for r in raw if r['arm'] != 'known_clap_unregularized']
    noisy = [r for r in base.read_csv(ROOT/'reports/noisy_controlled_benchmark/clean_trained_diagnostic/table1/per_example.csv')
             if r['arm'] == 'known_clap_unregularized' and r['snr_db'] == '30']
    new = base.read_csv(OUT/'per_example.csv')
    for r in (*raw, *noisy, *new):
        r['lsd_db'] = 20 * math.sqrt(float(r['stft_logmag_mse']))
    # Transform before any median or mean; not sqrt(mean log-MSE).
    noisy_records = task.reduce_rows(noisy, ('arm', 'provider', 'room_id', 'seed', 'sample_id'))
    seed_rooms = task.reduce_rows([*raw, *noisy_records, *new], ('arm', 'provider', 'room_id', 'seed'))
    rooms = task.reduce_rows(seed_rooms, ('arm', 'provider', 'room_id'))
    base.write_csv(OUT/'all_methods_per_room.csv', rooms)
    base.write_csv(OUT/'lsd_per_example.csv', [dict(arm=r['arm'], provider=r['provider'],
        room_id=r['room_id'], sample_id=r['sample_id'], seed=r['seed'],
        noise_draw=r.get('noise_draw', ''), stft_logmag_mse=r['stft_logmag_mse'], lsd_db=r['lsd_db'])
        for r in (*raw, *noisy, *new)])
    return rooms


def cell(mean, sd):
    def fmt(value):
        value = float(value)
        return f'{float(f"{value:.3g}"):.0f}' if abs(value) >= 1000 else f'{value:.3g}'
    return r'\shortstack{$' + fmt(mean) + r'$\\$\pm ' + fmt(sd) + '$}'


def table(summary):
    labels = {
        'known_clap_unregularized': r'\shortstack[l]{Known excitation,\\unregularized}',
        'known_clap_tikhonov': r'\shortstack[l]{Known excitation,\\Tikhonov}',
        'crop_3ms_tikhonov': r'\shortstack[l]{Cropped-excitation\\(3 ms) + Tikhonov}',
        task.ARM: r'\shortstack[l]{Cropped-excitation\\(6 ms) + Tikhonov}',
        'regression_1s': 'Neural regressor'}
    lines = [
        '% Generated by experiments/cropped_excitation_baseline_report.py; old six-metric results preserved in the companion CSV/table.',
        r'\begin{table}[t]', r'\centering\scriptsize', r'\setlength{\tabcolsep}{2pt}',
        r'\renewcommand{\arraystretch}{1.15}',
        r'\caption{Single-clap RIR estimation (mean $\pm$ sample SD across rooms). Measured: 54 rooms, or 51 for EDT; simulated: four Shoebox rooms with 92.88-ms valid support. LSD is the RMS dB difference over STFT bins and frames. Unregularized rows use 30-dB noisy inputs; other rows use the original no-added-noise condition.}',
        r'\label{tab:post-meeting-table1}',
        r'\resizebox{\columnwidth}{!}{%',
        r'\begin{tabular}{@{}llrrrr@{}}', r'\toprule',
        r'Set & Method & \shortstack{EDC\\(dB)} & \shortstack{$|\Delta\mathrm{EDT}|$\\(ms)} & \shortstack{LSD\\(dB)} & NRMSE \\',
        r'\midrule']
    for population in ('measured_pooled', 'shoebox'):
        for i, arm in enumerate(task.ORDER):
            r = next(r for r in summary if r['population'] == population and r['arm'] == arm)
            group = (r'\multirow{5}{*}[-4ex]{\rotatebox[origin=c]{90}{' +
                     ('Measured' if population == 'measured_pooled' else 'Simulated') + '}}') if i == 0 else ''
            cells = [cell(r[m], r[m+'_std']) for m in ('edc_rmse_db', 'abs_edt_error_ms', 'lsd_db', 'nrmse')]
            lines.append(' & '.join([group, labels[arm], *cells]) + r' \\[2pt]')
        if population == 'measured_pooled':
            lines.append(r'\midrule')
    lines += [r'\bottomrule', r'\end{tabular}%', '}', r'\end{table}']
    return '\n'.join(lines) + '\n'


def six_metric_table(summary):
    # Insert only the new rows; every existing numeric cell is verbatim.
    old = (OUT/'original/publication/single_clap_benchmark.tex').read_text()
    for population, prefix in [('measured_pooled', 'Measured pooled'), ('shoebox', 'Shoebox (92.88 ms)')]:
        r = next(r for r in summary if r['population'] == population and r['arm'] == task.ARM)
        added = ' & '.join([prefix, '6 ms crop + Tikhonov',
            *[task.original.pm(float(r[m]), float(r[m+'_std'])) for m in base.METRICS]]) + r' \\'
        anchor = prefix + ' & 1 s Regression'
        assert old.count(anchor) == 1
        old = old.replace(anchor, added + '\n' + anchor)
    return old.replace('tab:post-meeting-table1', 'tab:cropped-excitation-six-metrics')


def visual_review():
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import soundfile as sf
    from matplotlib.lines import Line2D
    protocol = json.loads((OUT/'protocol.json').read_text())
    audio = OUT/'audio'; audio.mkdir(exist_ok=True)
    fig, axes = plt.subplots(5, 2, figsize=(9, 11.5))
    paths = []
    for row, example in enumerate(protocol['examples']):
        provider, sid = example['provider'], example['sample_id']
        meta, y, target = next(r for r in task.load_records(provider, 'test') if r[0]['sample_id'] == sid)
        with np.load(OUT/'estimates'/f'{provider}.npz', allow_pickle=False) as d:
            estimate = d['estimate'][np.flatnonzero(d['sample_id'].astype(str) == sid)[0]]
        bound = int(example['bound'])
        target, estimate = target[:bound], estimate[:bound]
        time = np.arange(bound)/44100
        axes[row, 0].plot(time, estimate, color='#2877b5', lw=.6)
        axes[row, 0].plot(time, target, color='black', lw=.5, ls='--')
        axes[row, 0].set(xlabel='Time (s)', ylabel='Amplitude', xlim=(0,bound/44100), title=provider.upper()+' — '+example['room_id'])
        for signal, color, ls in [(estimate, '#2877b5', '-'), (target, 'black', '--')]:
            edc = base.edc_truncated(signal.astype(np.float64), bound)
            axes[row, 1].plot(time[:len(edc)], edc, color=color, lw=1, ls=ls)
        axes[row, 1].set(xlabel='Time (s)', ylabel='EDC (dB)', xlim=(0,bound/44100))
        for ax in axes[row]: ax.grid(alpha=.18)
        for name, signal in [('observation', y), ('excitation_6ms', task.excitation(y)),
                             ('rir_reference', target), ('rir_6ms', estimate)]:
            path=audio/f'{provider}_{name}.wav'
            sf.write(path, signal, 44100, subtype='FLOAT')
            paths.append(dict(provider=provider, sample_id=sid, type=name, path=str(path.relative_to(ROOT))))
    fig.legend(handles=[Line2D([],[],color='black',ls='--',label='Reference RIR'),
        Line2D([],[],color='#2877b5',label='6 ms crop + Tikhonov')],
        loc='lower center', ncol=2, frameon=False)
    fig.tight_layout(rect=(0,.035,1,1))
    for ext in ('pdf', 'png'):
        fig.savefig(ROOT/f'publication/figures/cropped_excitation_6ms_examples.{ext}', dpi=170)
    plt.close(fig)
    base.write_json(OUT/'example_audio.json', paths)


def main():
    if (OUT/'result.json').exists():
        raise FileExistsError('Report exists; preserve it.')
    rooms = derive_lsd()
    previous = base.read_csv(OUT/'original/publication/single_clap_benchmark.csv')
    new = [r for r in base.read_csv(OUT/'summary.csv') if r['population'] in ('measured_pooled','shoebox')]
    combined = [*previous, *new]
    summary = []
    checks = []
    for population in ('measured_pooled', 'shoebox'):
        for arm in task.ORDER:
            r = dict(next(r for r in combined if r['population']==population and r['arm']==arm))
            group = [v for v in rooms if v['arm']==arm and
                (v['provider']!='shoebox' if population=='measured_pooled' else v['provider']=='shoebox')]
            assert len(group) == (54 if population=='measured_pooled' else 4)
            for metric in base.METRICS:
                values = [v[metric] for v in group if math.isfinite(v[metric])]
                mean, sd = statistics.mean(values), statistics.stdev(values)
                assert math.isclose(float(r[metric]), mean, rel_tol=1e-13, abs_tol=1e-13), (population,arm,metric)
                assert math.isclose(float(r[metric+'_std']), sd, rel_tol=1e-13, abs_tol=1e-13)
            values = [v['lsd_db'] for v in group if math.isfinite(v['lsd_db'])]
            r.update(lsd_db=statistics.mean(values), lsd_db_std=statistics.stdev(values),
                     n_finite_rooms_lsd_db=len(values),
                     abs_edt_error_ms=1000*float(r['abs_edt_error_s']),
                     abs_edt_error_ms_std=1000*float(r['abs_edt_error_s_std']))
            summary.append(r)
            if arm != task.ARM:
                source = next(v for v in previous if v['population']==population and v['arm']==arm)
                for key, value in source.items():
                    assert r[key]==value, (population,arm,key)
                checks.append(dict(population=population,arm=arm,all_original_csv_fields_unchanged=True))
    main_tex = table(summary)
    six_tex = six_metric_table(summary)
    (OUT/'table1.tex').write_text(main_tex)
    (OUT/'table1_six_metrics.tex').write_text(six_tex)
    base.write_csv(OUT/'table1.csv', summary)
    columns = ('edc_rmse_db', 'abs_edt_error_ms', 'lsd_db', 'nrmse')
    md = ['| Set | Method | EDC (dB) | EDT error (ms) | LSD (dB) | NRMSE |',
          '|---|---|---:|---:|---:|---:|']
    for r in summary:
        md.append('| '+' | '.join([r['population'],task.LABELS[r['arm']],
            *[f"{float(r[m]):.6g} ± {float(r[m+'_std']):.6g}" for m in columns]])+' |')
    (OUT/'table1.md').write_text('\n'.join(md)+'\n')
    comparison = []
    for population in ('measured_pooled','shoebox'):
        a = next(r for r in summary if r['population']==population and r['arm']=='crop_3ms_tikhonov')
        b = next(r for r in summary if r['population']==population and r['arm']==task.ARM)
        reg = next(r for r in summary if r['population']==population and r['arm']=='regression_1s')
        for metric in columns:
            v3, v6 = float(a[metric]), float(b[metric])
            comparison.append(dict(population=population, metric=metric, mean_3ms=v3, mean_6ms=v6,
                std_3ms=float(a[metric+'_std']), std_6ms=float(b[metric+'_std']),
                better_crop='6ms' if v6<v3 else ('3ms' if v3<v6 else 'tie'),
                six_ms_relative_change_percent=100*(v6/v3-1),
                regression_mean=float(reg[metric]), six_ms_better_than_regression=v6<float(reg[metric])))
    base.write_csv(OUT/'crop_comparison.csv', comparison)
    # Validate the complete output before changing the publication exports.
    qa = OUT/'table_preview'; qa.mkdir(exist_ok=True)
    driver = '\n'.join([r'\documentclass[10pt,twocolumn]{article}',
        r'\usepackage[letterpaper,left=.75in,right=.75in,top=.5in,bottom=.5in]{geometry}',
        r'\setlength{\columnsep}{.25in}', r'\usepackage{booktabs,multirow,graphicx}',
        r'\pagestyle{empty}', r'\begin{document}',
        r'\input{'+str(OUT/'table1.tex')+'}', r'\end{document}'])
    (qa/'preview.tex').write_text(driver)
    for _ in range(2):
        proc = subprocess.run(['pdflatex','-interaction=nonstopmode','-halt-on-error','preview.tex'],
            cwd=qa,capture_output=True,text=True)
        (qa/'compile.log').write_text(proc.stdout+proc.stderr)
        assert proc.returncode==0, proc.stdout[-3000:]
    log=(qa/'preview.log').read_text()
    assert 'Overfull' not in log and 'Undefined control sequence' not in log
    shutil.copyfile(qa/'preview.pdf', OUT/'table1.pdf')
    six_driver = driver.replace(str(OUT/'table1.tex'), str(OUT/'table1_six_metrics.tex'))
    (qa/'six_metrics.tex').write_text(six_driver)
    for _ in range(2):
        proc = subprocess.run(['pdflatex','-interaction=nonstopmode','-halt-on-error','six_metrics.tex'],
            cwd=qa,capture_output=True,text=True)
        (qa/'six_metrics_compile.log').write_text(proc.stdout+proc.stderr)
        assert proc.returncode==0, proc.stdout[-3000:]
    shutil.copyfile(qa/'six_metrics.pdf', PUB/'post_meeting_table1_six_metrics.pdf')
    for ext in ('tex','csv','md','pdf'):
        shutil.copyfile(OUT/('table1.'+ext), PUB/('single_clap_benchmark.'+ext))
        shutil.copyfile(OUT/('table1.'+ext), ROOT/'reports/single_clap_benchmark'/('table1.'+ext))
    shutil.copyfile(OUT/'table1_six_metrics.tex',PUB/'post_meeting_table1_six_metrics.tex')
    visual_review()
    lamb = json.loads((OUT/'selected_lambda.json').read_text())
    success = all(not r['six_ms_better_than_regression'] for r in comparison)
    result=dict(id='CROPPED_EXCITATION_6MS',
        x_decision='Assess crop-window sensitivity before revising the paper narrative.',
        prediction='No preferred ordering required; compare all four requested metrics in both populations.',
        observed=comparison, verdict='PASS' if success else 'FAIL',
        verdict_definition='Descriptive check: existing Regression has no larger mean error than the new 6-ms baseline on all eight population/metric comparisons. Not statistical significance or seed robustness.',
        selected_lambda=lamb, original_rows_unchanged=checks,
        original_source_results_unchanged=True, no_retraining=True, no_existing_estimator_reinference=True,
        no_manuscript_narrative_edits=True, lsd_derived_from_existing_per_record_logmag=True,
        source_condition='6-ms and3-ms use same original no-added-noise data; unregularized rows retain previously authorized30-dB source.',
        table_sha256=base.sha(PUB/'single_clap_benchmark.tex'), visual_review_status='pending')
    base.write_json(OUT/'result.json',result)
    report = ['# Six-millisecond cropped-excitation control','',
        f"Validation-selected relative lambda: **{lamb['lambda_relative']:.12g}**, from {lamb['n_validation_records']} validation records; median validation NRMSE {lamb['median_nrmse']:.8g}.",
        '', 'Only the 6-ms estimator was evaluated. It uses265samples (6.00907ms), the same stored one-second observation as3ms, unchanged FFT131072 inversion, independent selection on the original11-value grid, and original support-aware test metrics. No new noise was added. Historical lambda-selection NRMSE includes the padded one-second horizon; TEST scoring uses actual support, including4096samples for Shoebox.',
        '', 'All48 original metric means and48SDs remain unchanged in the CSV and six-metric companion. The compact table converts EDT seconds to milliseconds. LSD is calculated as20*sqrt(per-record log-magMSE), then aggregated; it is not20*sqrt(pooled meanMSE). STFT: periodic Hann510,hop127,reference-peak -80dB floor, same valid support.',
        '', 'Aggregation: median noise draws when applicable, median records within seed/room, median training seeds within room, then equal-room arithmetic mean and sampleSD(ddof1). Measured54rooms (EDT51); Shoebox4. No provider median averaging.',
        '', '## Crop comparison', '', '| Population | Metric | 3ms mean | 6ms mean | Lower error |', '|---|---|---:|---:|---|']
    for r in comparison:
        report.append(f"| {r['population']} | {r['metric']} | {r['mean_3ms']:.6g} | {r['mean_6ms']:.6g} | {r['better_crop']} |")
    report += ['', 'Publication: `publication/paper/tables/single_clap_benchmark.{tex,csv,md,pdf}`; full original six metrics plus6ms: `publication/paper/tables/post_meeting_table1_six_metrics.tex`. Diagnostics: `publication/figures/cropped_excitation_6ms_examples.{pdf,png}` and this report’s `audio/`. Input-only examples were frozen by sample-ID hash, one perprovider. No reference-based example selection.',
        '', 'The existing unregularized rows retain their previously authorized30-dB source while other rows use no-added-noise source data. This addition does not turn the mixed-source table into a common-noise comparison. Existing training seeds and checkpoints are unchanged. Main manuscript text was not edited.']
    (OUT/'README.md').write_text('\n'.join(report)+'\n')
    print(json.dumps(dict(lambda_selected=lamb,comparison=comparison),indent=2),flush=True)
    print('VERDICT CROPPED_EXCITATION_6MS',result['verdict'], 'Descriptive comparison complete; manuscript narrative unchanged.',flush=True)


if __name__=='__main__':
    main()
